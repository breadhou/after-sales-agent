def build_worker_environment(model_environment: dict[str, str], actor_token: str | None,
        base_url: str, manifest_path: Path | None, parent_environment: dict[str, str]) -> dict[str, str]:
    windows = os.name == 'nt'
    runtime_keys = {key.upper() if windows else key: key for key in RUNTIME_KEYS}
    environment = {}
    # dict(os.environ) normalizes Windows names; emit only the canonical whitelist keys.
    for key, value in parent_environment.items():
        inherited_key = runtime_keys.get(key.upper() if windows else key)
        if inherited_key is not None: environment[inherited_key] = value
    environment.update({key: model_environment[key] for key in MODEL_KEYS if key in model_environment})
    environment['SUPERMALL_BASE_URL'] = base_url
    if actor_token is not None:
        if not actor_token.strip(): raise ValueError('Missing current fixture token')
        environment['SUPERMALL_TOKEN'] = actor_token
    if manifest_path is not None: environment['DEMO_PRODUCT_MANIFEST'] = str(manifest_path)
    return environment


def _read_json(path): return strict_json(Path(path).read_text(encoding='utf-8-sig'))


def _hash(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False,
        separators=(',', ':'), allow_nan=False).encode('utf-8')).hexdigest()


def _exclusive_json(path, value):
    with Path(path).open('x', encoding='utf-8') as stream:
        json.dump(value, stream, ensure_ascii=False, separators=(',', ':'), allow_nan=False)
        stream.flush(); os.fsync(stream.fileno())


def _confined(root, relative, *, must_exist=True):
    if not isinstance(relative, str) or not relative or '\\' in relative or ':' in relative:
        raise ValueError('Invalid confined path')
    parts = relative.split('/')
    if PurePosixPath(relative).is_absolute() or any(part in ('', '.', '..') for part in parts):
        raise ValueError('Invalid confined path')
    root = Path(root).resolve(strict=True)
    candidate = root.joinpath(*parts)
    actual = candidate.resolve(strict=must_exist)
    if not actual.is_relative_to(root) or actual != candidate:
        raise ValueError('Evidence path escapes its owner')
    return actual


def _initialize_batch(manifest_path, run_dir, resume):
    manifest = contract.validate_wire('Manifest', _read_json(manifest_path))
    cases = contract.load_suite(manifest_path)
    hashes = {case['caseId']: _hash(case) for case in cases}
    run_dir = Path(run_dir).absolute()
    allowed = (REPO_ROOT / 'eval/runs').resolve()
    if run_dir.resolve() != run_dir or run_dir.parent != allowed or not contract.SAFE_ID_RE.fullmatch(run_dir.name):
        raise ValueError('Run directory must be a direct confined eval/runs child')
    state_path = run_dir / 'batch.json'
    options = _OPTIONS.get()
    config_hash = _hash(dict(supermallRoot=str(Path(options.get('supermall_root', REPO_ROOT.parent / 'supermall')).resolve()),
        backendEnvFile=str(Path(options.get('backend_env_file', REPO_ROOT / '.env')).resolve()),
        deadlineSeconds=DEADLINE_SECONDS, workerEntry='com.mall.agent.evaluation.EvaluationMain'))
    if resume:
        state = _read_json(state_path)
        if state.get('schemaVersion') != 1 or state.get('runId') != run_dir.name or state.get('manifestHash') != _hash(manifest) or state.get('caseHashes') != hashes or state.get('configHash') != config_hash:
            raise ValueError('Resume version or configuration mismatch')
        return state
    if run_dir.exists(): raise ValueError('Run ID cannot be reused')
    run_dir.mkdir(parents=True)
    _exclusive_json(run_dir / 'manifest.json', manifest)
    _exclusive_json(run_dir / 'cases.json', {'cases': cases})
    trials = []
    for case_id in manifest['caseIds']:
        trials.append(dict(trialId='trial-' + uuid.uuid4().hex, caseId=case_id, trialKind='FIRST', repeatIndex=0, state='PENDING'))
        if case_id in manifest['repeatIds']:
            for index in (1, 2):
                trials.append(dict(trialId='trial-' + uuid.uuid4().hex, caseId=case_id, trialKind='REPEAT', repeatIndex=index, state='PENDING'))
    state = dict(schemaVersion=1, runId=run_dir.name, manifestHash=_hash(manifest), caseHashes=hashes,
        configHash=config_hash, trials=trials, stopReason=None)
    _atomic_json(state_path, state)
    return state


def _error_result(run_id, trial, category, *, skipped=False):
    status = 'SKIPPED' if skipped else 'ERROR'
    return contract.validate_wire('TrialResult', dict(schemaVersion=1, runId=run_id,
        caseId=trial['caseId'], trialId=trial['trialId'], status=status, automaticStatus=status,
        failedCriteria=[category], manualReview='NOT_REQUIRED'))


def _message(op, run_id, trial, **payload):
    return contract.validate_wire('FixtureRequest', dict(schemaVersion=1, op=op, runId=run_id,
        caseId=trial['caseId'], trialId=trial['trialId'], **payload))


def _manual_records(run_dir):
    path = run_dir / 'manual-audit.jsonl'
    if not path.exists(): return {}
    records = {}
    for line in path.read_text(encoding='utf-8-sig').splitlines():
        value = strict_json(line)
        if not isinstance(value, dict) or set(value) != {'caseId', 'trialId', 'criteria'} or not isinstance(value['criteria'], dict) or any(v not in ('PASS', 'FAIL') for v in value['criteria'].values()):
            raise ValueError('Invalid human audit file')
        key = (value['caseId'], value['trialId'])
        if key in records: raise ValueError('Duplicate human audit')
        records[key] = value
    return records


def _synthetic_bindings(case, run_id, trial_id):
    # reviewInput is frozen synthetic input, never business Oracle evidence.
    order_id = case['reviewInput']['candidateAction']['orderId']
    orders = {'order-a': dict(orderId=order_id, orderNo='SYNTHETIC')}
    return contract.validate_wire('Bindings', dict(schemaVersion=1, runId=run_id, caseId=case['caseId'],
        trialId=trial_id, activeActor=None, actors={}, orders=orders, products={}))


def _load_worker_evidence(worker, work_dir, run_id, case_id, trial_id):
    worker = contract.validate_wire('WorkerResult', worker)
    if any(worker[key] != value for key, value in (('runId', run_id), ('caseId', case_id), ('trialId', trial_id))):
        raise ValueError('Wrong worker identity')
    event_path = _confined(work_dir, worker['eventsFile'])
    _confined(work_dir, worker['privateEvidenceFile'])
    events = [contract.validate_wire('Event', strict_json(line)) for line in event_path.read_text(encoding='utf-8').splitlines()]
    if any(any(event[key] != worker[key] for key in ('runId', 'caseId', 'trialId')) for event in events) or [e['sequence'] for e in events] != list(range(1, len(events)+1)):
        raise ValueError('Wrong worker event identity or sequence')
    return worker, events


def _run_worker(config_path, environment, trial_root):
    jar = REPO_ROOT / 'agent/target/agent.jar'
    if not jar.is_file(): raise ValueError('Missing packaged evaluation worker')
    java = str(Path(environment['JAVA_HOME']) / 'bin/java.exe') if os.name == 'nt' and environment.get('JAVA_HOME') else 'java'
    command = [java, '-Dstdout.encoding=UTF-8', '-Dstderr.encoding=UTF-8', '-cp', str(jar),
               'com.mall.agent.evaluation.EvaluationMain', '--config', str(config_path)]
    started = time.monotonic()
    owned = None
    with (trial_root / 'worker.stdout').open('x', encoding='utf-8') as stdout, (trial_root / 'worker.stderr').open('x', encoding='utf-8') as stderr:
        try:
            owned = OwnedProcess(command, cwd=REPO_ROOT, environment=environment, stdout=stdout, stderr=stderr)
            try: exit_code = owned.process.wait(timeout=DEADLINE_SECONDS)
            except subprocess.TimeoutExpired: exit_code = None
        finally:
            terminated = owned.close() if owned else True
    duration = int((time.monotonic()-started)*1000)
    record = dict(exitCode=exit_code, terminated=terminated, durationMs=duration)
    _exclusive_json(trial_root / 'process.json', record)
    if not terminated or exit_code is None or exit_code != 0: return None, duration, terminated
    lines = (trial_root / 'worker.stdout').read_text(encoding='utf-8').splitlines()
    if len(lines) != 1: raise ValueError('Worker stdout is not one strict protocol result')
    return contract.validate_wire('WorkerResult', strict_json(lines[0])), duration, terminated


