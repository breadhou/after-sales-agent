def _request(client, message, path):
    reply = contract.validate_wire('FixtureReply', client.request(message))
    if reply['op'] != message['op']: raise ValueError('Wrong helper operation')
    _exclusive_json(path, dict(request=message, reply=reply))
    return reply


def _supplement(state, run_dir, case_id, reason):
    if not isinstance(reason, str) or not reason.startswith('infrastructure:') or not reason[len('infrastructure:'):].strip():
        raise ValueError('Supplement requires an explicit infrastructure reason')
    originals = [t for t in state['trials'] if t['caseId'] == case_id and t['trialKind'] == 'FIRST']
    if len(originals) != 1: raise ValueError('Supplement case has no first attempt')
    old = originals[0]
    result = contract.validate_wire('TrialResult', _read_json(run_dir / old['trialId'] / 'result.json'))
    if old['state'] != 'COMPLETE' or old.get('terminated') is not True or old.get('terminalEvidence') not in ('NOT_SENT', 'COMPLETED') or result['status'] != 'ERROR' or not set(result['failedCriteria']).intersection(INFRA_CRITERIA):
        raise ValueError('Supplement needs a verified old write and an infrastructure failure')
    if any(t['state'] == 'INFLIGHT' for t in state['trials']) or state.get('stopReason') == 'UNRESOLVED_WRITE':
        raise ValueError('Unresolved writes forbid supplements')
    trial = dict(trialId='supplement-' + uuid.uuid4().hex, caseId=case_id, trialKind='SUPPLEMENT',
                 repeatIndex=0, state='PENDING', reason=reason, supplements=old['trialId'])
    state['trials'].append(trial)
    _atomic_json(run_dir / 'batch.json', state)
    return [trial]


def _execute_trial(case, trial, state, run_dir, client, backend_output, model, base_url, ledger, manual):
    run_id = state['runId']; trial_id = trial['trialId']; directory = run_dir / trial_id
    if directory.exists(): raise ValueError('Trial directory cannot be reused')
    backend = case.get('control', {}).get('target') == 'BACKEND_TRANSACTION'
    real_model = not backend and (case['mode'] != 'CONTROLLED' or case['control']['usesRealModel'])
    allowance = ledger.reserve(run_id + '.' + trial_id, 12 if real_model else 0)
    directory.mkdir()
    work = directory / 'work'; work.mkdir()
    trial.update(state='INFLIGHT', terminated=False, terminalEvidence='UNKNOWN')
    _atomic_json(run_dir / 'batch.json', state)
    before = after = {}; events = []; worker = {}; terminated = True; terminal = 'NOT_SENT'
    duration = None; fixture_duration = None; result = None; dispatched = False; fixture_started = time.monotonic()
    try:
        _exclusive_json(directory / 'case.json', case)
        if case['mode'] == 'REVIEW_ONLY':
            bindings = _synthetic_bindings(case, run_id, trial_id)
            before = after = dict(orders={}, terminalEvidence='NOT_SENT')
            _exclusive_json(directory / 'oracle-scope.json', {'kind': 'SYNTHETIC_REVIEW', 'databaseProof': False})
        else:
            terminal = 'UNKNOWN'
            prepared = _request(client, _message('prepare', run_id, trial, fixture=case['fixture']), directory / 'prepare.json')
            if prepared['status'] != 'COMPLETED':
                terminal = 'UNKNOWN' if prepared['status'] in ('UNKNOWN', 'PREPARED') else 'NOT_SENT'
                raise ValueError('Fixture preparation did not complete')
            terminal = 'NOT_SENT'
            expected_prefix = '/'.join((run_id, case['caseId'], trial_id)) + '/'
            if prepared['ledgerPath'] != expected_prefix + 'ledger.json' or prepared['bindingFile'] != expected_prefix + 'bindings.json':
                raise ValueError('Fixture paths do not match trial owner')
            binding_path = _confined(backend_output, prepared['bindingFile'])
            bindings = contract.validate_wire('Bindings', _read_json(binding_path))
            if any(bindings[k] != v for k, v in (('runId', run_id), ('caseId', case['caseId']), ('trialId', trial_id))) or bindings['activeActor'] != case['fixture']['activeActor']:
                raise ValueError('Fixture binding identity mismatch')
            reply = _request(client, _message('oracle', run_id, trial, ledgerPath=prepared['ledgerPath'], terminalEvidence='NOT_SENT'), directory / 'before-reply.json')
            if reply['status'] != 'COMPLETED': raise ValueError('Before Oracle unavailable')
            before = contract.validate_wire('Oracle', reply['oracle'])
        _exclusive_json(directory / 'helper-bindings.json', bindings)
        worker_bindings = copy.deepcopy(bindings)
        for product in worker_bindings['products'].values():
            product['skus'] = {alias: sku['skuId'] for alias, sku in product['skus'].items()}
        _exclusive_json(directory / 'bindings.json', worker_bindings)
        manifest = {alias: int(product['productId']) for alias, product in bindings['products'].items()}
        _exclusive_json(directory / 'products.json', manifest)
        _exclusive_json(directory / 'before.json', before)
        if backend:
            dispatched = True; terminal = 'UNKNOWN'
            reply = _request(client, _message('probe', run_id, trial, ledgerPath=prepared['ledgerPath'], probe=case['control']['probe']), directory / 'probe-reply.json')
            _exclusive_json(work / 'probe.json', dict(schemaVersion=1, runId=run_id, caseId=case['caseId'], trialId=trial_id, fixtureReply=reply))
            if reply['status'] != 'COMPLETED': raise ValueError('Probe did not complete')
            terminal = 'UNKNOWN' if reply['probeEvidence']['receiptClass'] == 'UNKNOWN' else 'COMPLETED'
        else:
            config = contract.validate_wire('WorkerConfig', dict(schemaVersion=1, runId=run_id, caseId=case['caseId'],
                trialId=trial_id, caseFile='case.json', bindingFile='bindings.json', productManifest='products.json',
                workDir='work', **allowance))
            _exclusive_json(directory / 'config.json', config)
            token = bindings['actors'][bindings['activeActor']]['userToken'] if bindings['activeActor'] is not None else None
            environment = build_worker_environment(model, token, base_url, directory / 'products.json', dict(os.environ))
            fixture_duration = int((time.monotonic()-fixture_started)*1000)
            dispatched = True; terminal = 'NOT_SENT' if case['mode'] == 'REVIEW_ONLY' else 'UNKNOWN'; terminated = False
            raw, duration, terminated = _run_worker(directory / 'config.json', environment, directory)
            if raw is None: raise ValueError('Worker result unavailable')
            worker, events = _load_worker_evidence(raw, work, run_id, case['caseId'], trial_id)
            _exclusive_json(directory / 'worker.json', worker)
            if case['mode'] == 'REVIEW_ONLY' and worker['terminalEvidence'] != 'NOT_SENT':
                raise ValueError('Synthetic review cannot claim a business write')
            terminal = worker['terminalEvidence']
            ledger.complete(run_id + '.' + trial_id, worker['metering'], terminated)
        if case['mode'] != 'REVIEW_ONLY':
            reply = _request(client, _message('oracle', run_id, trial, ledgerPath=prepared['ledgerPath'], terminalEvidence=terminal), directory / 'after-reply.json')
            if reply['status'] != 'COMPLETED': terminal = 'UNKNOWN'; raise ValueError('After Oracle unavailable')
            after = contract.validate_wire('Oracle', reply['oracle'])
            if after['terminalEvidence'] != terminal: terminal = 'UNKNOWN'; raise ValueError('After Oracle terminal mismatch')
        _exclusive_json(directory / 'after.json', after)
        with evidence_scope(work):
            if backend:
                with backend_probe_scope(Path('probe.json'), run_id=run_id, trial_id=trial_id):
                    result = judge(case, [], before, after, {}, None)
            else: result = judge(case, events, before, after, worker, manual)
    except Exception as failure:
        _exclusive_json(directory / 'runner-error.json', {'exceptionClass': type(failure).__name__})
        if dispatched and case['mode'] != 'REVIEW_ONLY' and not after and not (directory / 'after-reply.json').exists():
            # A read-only projection cannot resolve an in-flight write. Preserve
            # UNKNOWN even when the independent query currently sees no rows.
            try:
                reply = _request(client, _message('oracle', run_id, trial,
                    ledgerPath=prepared['ledgerPath'], terminalEvidence=terminal), directory / 'after-reply.json')
                if reply['status'] == 'COMPLETED':
                    after = contract.validate_wire('Oracle', reply['oracle'])
                    if after['terminalEvidence'] != terminal: raise ValueError('Oracle terminal mismatch')
                    _exclusive_json(directory / 'after.json', after)
            except Exception as oracle_failure:
                terminal = 'UNKNOWN'
                _exclusive_json(directory / 'oracle-error.json', {'exceptionClass': type(oracle_failure).__name__})
        category = 'UNRESOLVED_WRITE' if terminal == 'UNKNOWN' else 'MISSING_EVIDENCE' if dispatched else 'FIXTURE_ERROR'
        result = _error_result(run_id, trial, category)
    if not dispatched or backend:
        ledger.complete(run_id + '.' + trial_id, dict(logicalModelRequests=0, promptTokens=None, completionTokens=None,
            totalTokens=None, usageComplete=True, unknownUsageRequests=0), terminated)
    if backend: fixture_duration = int((time.monotonic()-fixture_started)*1000)
    if terminal == 'UNKNOWN' or not terminated:
        result = _error_result(run_id, trial, 'UNRESOLVED_WRITE')
        state['stopReason'] = 'UNRESOLVED_WRITE'
    _exclusive_json(directory / 'result.json', result)
    metadata = dict(caseId=case['caseId'], trialKind=trial['trialKind'], repeatIndex=trial['repeatIndex'],
        events=events, worker=worker, before=before, after=after,
        workerDurationMs=duration, fixtureDurationMs=fixture_duration)
    _exclusive_json(directory / 'metadata.json', metadata)
    trial.update(state='COMPLETE', terminated=terminated, terminalEvidence=terminal)
    _atomic_json(run_dir / 'batch.json', state)
    return result


def _load_saved_run(run_dir):
    """Verify parent snapshots whose hashes were frozen after load_suite validation."""
    run_dir = Path(run_dir).absolute()
    if run_dir.resolve(strict=True) != run_dir or not run_dir.is_dir():
        raise ValueError('Invalid saved run directory')
    state = _read_json(_confined(run_dir, 'batch.json'))
    manifest = contract.validate_wire('Manifest', _read_json(_confined(run_dir, 'manifest.json')))
    saved = _read_json(_confined(run_dir, 'cases.json'))
    if not isinstance(saved, dict) or set(saved) != {'cases'} or not isinstance(saved['cases'], list):
        raise ValueError('Invalid frozen cases')
    cases = [contract.validate_case(case) for case in saved['cases']]
    if state.get('schemaVersion') != 1 or state.get('runId') != run_dir.name or state.get('manifestHash') != _hash(manifest) or state.get('caseHashes') != {c['caseId']: _hash(c) for c in cases} or [c['caseId'] for c in cases] != manifest['caseIds']:
        raise ValueError('Saved frozen suite hash mismatch')
    seen = set()
    for trial in state['trials']:
        if not isinstance(trial.get('trialId'), str) or not contract.SAFE_ID_RE.fullmatch(trial['trialId']) or trial['trialId'] in seen or trial['caseId'] not in state['caseHashes'] or trial['state'] not in ('PENDING', 'INFLIGHT', 'COMPLETE'):
            raise ValueError('Invalid saved trial identity or state')
        seen.add(trial['trialId'])
    return state, cases, manifest


def _assess_trial(case, trial, state, directory, original, metadata, manual):
    """Rejudge actual archived proof; the first automatic verdict remains a floor."""
    run_id, trial_id = state['runId'], trial['trialId']
    try:
        frozen = contract.validate_case(_read_json(_confined(directory, 'case.json')))
        if _hash(frozen) != state['caseHashes'][trial['caseId']]: raise ValueError('Wrong saved trial case')
        if metadata['caseId'] != trial['caseId'] or metadata['trialKind'] != trial['trialKind'] or metadata['repeatIndex'] != trial['repeatIndex']:
            raise ValueError('Wrong saved trial classification')
        before = _read_json(_confined(directory, 'before.json')) if metadata['before'] else {}
        after = _read_json(_confined(directory, 'after.json')) if metadata['after'] else {}
        if before != metadata['before'] or after != metadata['after']: raise ValueError('Oracle differs from saved metadata')
        work = _confined(directory, 'work')
        with evidence_scope(work):
            if case.get('control', {}).get('target') == 'BACKEND_TRANSACTION':
                if metadata['worker'] or metadata['events'] or metadata['workerDurationMs'] is not None:
                    raise ValueError('Invented probe worker evidence')
                with backend_probe_scope(Path('probe.json'), run_id=run_id, trial_id=trial_id):
                    result = judge(case, [], before, after, {}, None)
            else:
                worker, events = _load_worker_evidence(_read_json(_confined(directory, 'worker.json')),
                    work, run_id, case['caseId'], trial_id)
                if worker != metadata['worker'] or events != metadata['events']:
                    raise ValueError('Worker differs from saved metadata')
                if case['mode'] == 'REVIEW_ONLY':
                    scope = _read_json(_confined(directory, 'oracle-scope.json'))
                    if scope != {'kind': 'SYNTHETIC_REVIEW', 'databaseProof': False} or worker['terminalEvidence'] != 'NOT_SENT':
                        raise ValueError('Invalid synthetic review scope')
                result = judge(case, events, before, after, worker, manual)
    except (OSError, UnicodeError, ValueError, KeyError, TypeError, ArithmeticError):
        result = _error_result(run_id, trial, 'MISSING_EVIDENCE')
    # Human audit completes only the manual portion. It cannot clear a saved
    # automatic failure, unresolved write, missing proof or unverified process.
    automatic = original['automaticStatus']
    result['automaticStatus'] = automatic
    if automatic != 'PASS':
        manual_ids = {c['criterionId'] for c in case['manualRubric']['criteria']}
        old_failures = set(original['failedCriteria']) - manual_ids - {'MANUAL_REQUIRED', 'MANUAL_INVALID', 'MANUAL_FAIL'}
        result['failedCriteria'] = sorted(set(result['failedCriteria']) | old_failures)
        if automatic == 'ERROR': result['status'] = 'ERROR'
        elif automatic == 'FAIL' and result['status'] != 'ERROR': result['status'] = 'FAIL'
        elif automatic == 'SKIPPED' and result['status'] == 'PASS': result['status'] = 'SKIPPED'
    if trial.get('terminated') is not True or trial.get('terminalEvidence') == 'UNKNOWN':
        result['status'] = 'ERROR'
        result['failedCriteria'] = sorted(set(result['failedCriteria']) | {'UNRESOLVED_WRITE'})
    return contract.validate_wire('TrialResult', result)


def _assess_saved_run(run_dir, output_path=None):
    """Read-only source assessment, with separate private derived results/report."""
    run_dir = Path(run_dir).absolute()
    state, cases, manifest = _load_saved_run(run_dir)
    output = Path(output_path).absolute() if output_path is not None else None
    if output is not None:
        if output.suffix.lower() not in ('.md', '.json') or output.exists() or output.is_symlink() or output.resolve() != output or not output.parent.is_dir() or (output.is_relative_to(run_dir) and output.parent != run_dir):
            raise ValueError('Report must be a new MD/JSON file outside original trace directories')
    manual = _manual_records(run_dir)
    results = []; metadata = {}
    by_id = {case['caseId']: case for case in cases}
    for trial in state['trials']:
        if trial['state'] == 'COMPLETE':
            directory = _confined(run_dir, trial['trialId'])
            original = contract.validate_wire('TrialResult', _read_json(_confined(directory, 'result.json')))
            if any(original[key] != value for key, value in (('runId', state['runId']), ('caseId', trial['caseId']), ('trialId', trial['trialId']))):
                raise ValueError('Wrong saved result identity')
            data = _read_json(_confined(directory, 'metadata.json'))
            result = _assess_trial(by_id[trial['caseId']], trial, state, directory, original, data,
                manual.get((trial['caseId'], trial['trialId'])))
            results.append(result)
            metadata[(state['runId'], trial['trialId'])] = data
    with summary_scope({c['caseId']: c for c in cases}, metadata): summary = summarize(results, manifest)
    assessment_root = _confined(run_dir, 'assessments', must_exist=False)
    assessment_root.mkdir(exist_ok=True)
    assessment = assessment_root / ('assessment-' + uuid.uuid4().hex); assessment.mkdir()
    results_path = assessment / 'results.json'
    _exclusive_json(results_path, dict(schemaVersion=1, results=results))
    output = output or assessment / 'report.json'
    export_report(summary, output)
    return dict(completedTrials=len(results), resultsFile=str(results_path), reportFile=str(output))


def _saved_report(state, run_dir, cases, manifest, budget):
    assessed = _assess_saved_run(run_dir)
    return dict(dryRun=False, runId=state['runId'], plannedTrials=len(state['trials']),
        completedTrials=assessed['completedTrials'], stopReason=state['stopReason'], budget=budget.snapshot(), reportFile=assessed['reportFile'])


def run_batch(manifest_path: Path, run_dir: Path, execute: bool, resume: bool,
              supplement_case: str | None = None, reason: str | None = None) -> dict:
    manifest_path = Path(manifest_path); run_dir = Path(run_dir).absolute()
    manifest = contract.validate_wire('Manifest', _read_json(manifest_path))
    cases = contract.load_suite(manifest_path)
    if (supplement_case is None) != (reason is None): raise ValueError('Supplement case and reason must be supplied together')
    if not execute:
        return dict(dryRun=True, plannedTrials=len(cases)+2*len(manifest['repeatIds']),
                    phase=manifest['phase'], suiteVersion=manifest['suiteVersion'])
    runs_root = REPO_ROOT / 'eval/runs'
    with file_lock(runs_root / 'batch-dispatch.lock'):
        state = _initialize_batch(manifest_path, run_dir, resume)
        budget = BudgetLedger(runs_root / 'budget-ledger.json')
        if supplement_case is not None:
            if not resume: raise ValueError('Supplement requires resume of its first batch')
            selected = _supplement(state, run_dir, supplement_case, reason)
        else: selected = state['trials']
        if any(t['state'] == 'INFLIGHT' for t in state['trials']):
            return dict(dryRun=False, stopReason='INFLIGHT', budget=budget.snapshot())
        if state.get('stopReason') == 'UNRESOLVED_WRITE':
            return dict(dryRun=False, stopReason='UNRESOLVED_WRITE', budget=budget.snapshot())
        # Unverified old process/creation actions also block another run in this group.
        for other in runs_root.glob('*/batch.json'):
            old = _read_json(other)
            if old.get('stopReason') == 'UNRESOLVED_WRITE' or any(t['state'] == 'INFLIGHT' for t in old['trials']):
                return dict(dryRun=False, stopReason='UNRESOLVED_WRITE', budget=budget.snapshot())
        pending = [t for t in selected if t['state'] == 'PENDING']
        if not pending: return _saved_report(state, run_dir, cases, manifest, budget)
        manual = _manual_records(run_dir)
        model = _read_env_file(REPO_ROOT / '.env', set(MODEL_KEYS) | {'SUPERMALL_BASE_URL'})
        for key in MODEL_KEYS:
            if key in os.environ: model[key] = os.environ[key]
        base_url = model.pop('SUPERMALL_BASE_URL', None) or os.environ.get('SUPERMALL_BASE_URL', 'http://localhost:8081')
        runtime = dict(model={key:model[key] for key in MODEL_KEYS if key in model},baseUrl=base_url,
            artifacts={name:hashlib.sha256((REPO_ROOT/name).read_bytes()).hexdigest() if (REPO_ROOT/name).is_file() else None
                for name in ('agent/target/agent.jar','mcp-server/target/mcp-server.jar')})
        runtime_hash = _hash(runtime)
        if state.get('runtimeHash') is not None and state['runtimeHash'] != runtime_hash:
            raise ValueError('Resume worker/model configuration mismatch')
        state['runtimeHash'] = runtime_hash
        _atomic_json(run_dir / 'batch.json', state)
        options = _OPTIONS.get(); client = None; backend_output = None
        try:
            if any(c['mode'] != 'REVIEW_ONLY' for c in cases if c['caseId'] in {t['caseId'] for t in pending}):
                client, backend_output = _helper(run_dir, options)
                reply = _request(client, _message('preflight', state['runId'], pending[0]), run_dir / ('preflight-' + uuid.uuid4().hex + '.json'))
                if reply['status'] != 'COMPLETED': raise ValueError('Fixture preflight failed')
            by_id = {c['caseId']: c for c in cases}
            for trial in pending:
                if budget.snapshot()['unresolvedReservations']:
                    state['stopReason'] = 'INFLIGHT'; break
                try:
                    _execute_trial(by_id[trial['caseId']], trial, state, run_dir, client, backend_output,
                        model, base_url, budget, manual.get((trial['caseId'], trial['trialId'])))
                except BudgetStop:
                    state['stopReason'] = 'BUDGET_STOP'; break
                if state['stopReason'] == 'UNRESOLVED_WRITE': break
        except Exception as failure:
            _exclusive_json(run_dir / ('batch-error-' + uuid.uuid4().hex + '.json'), {'exceptionClass': type(failure).__name__})
            state['stopReason'] = 'FIXTURE_ERROR'
        finally:
            if client:
                try:
                    if state['stopReason'] != 'UNRESOLVED_WRITE':
                        _request(client, _message('shutdown', state['runId'], pending[0]), run_dir / ('shutdown-' + uuid.uuid4().hex + '.json'))
                except Exception: state['stopReason'] = state['stopReason'] or 'FIXTURE_ERROR'
                if not client.close(): state['stopReason'] = 'UNRESOLVED_WRITE'
            _atomic_json(run_dir / 'batch.json', state)
        return _saved_report(state, run_dir, cases, manifest, budget)


def main(argv=None):
    parser = argparse.ArgumentParser(description='Private evaluation batch runner (default: dry run)')
    parser.add_argument('--manifest', required=True, type=Path)
    parser.add_argument('--run-dir', required=True, type=Path)
    parser.add_argument('--execute', action='store_true')
    parser.add_argument('--resume', action='store_true')
    parser.add_argument('--supermall-root', type=Path, default=REPO_ROOT.parent / 'supermall')
    parser.add_argument('--backend-env-file', type=Path, default=REPO_ROOT / '.env')
    parser.add_argument('--supplement-case')
    parser.add_argument('--reason')
    args = parser.parse_args(argv)
    token = _OPTIONS.set(dict(supermall_root=args.supermall_root, backend_env_file=args.backend_env_file))
    try:
        result = run_batch(args.manifest, args.run_dir, args.execute, args.resume, args.supplement_case, args.reason)
        print(json.dumps(result, separators=(',', ':')))
        return 0
    except Exception as failure:
        print(json.dumps({'status': 'ERROR', 'exceptionClass': type(failure).__name__}, separators=(',', ':')))
        return 1
    finally: _OPTIONS.reset(token)


if __name__ == '__main__': raise SystemExit(main())
